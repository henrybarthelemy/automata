/**
 * Hensel notation: the 51 isotropic neighbourhood classes of the Moore
 * neighbourhood.
 *
 * A neighbourhood is an 8-bit mask laid out around the centre cell as
 *
 *     7 6 5
 *     4 . 3
 *     2 1 0
 *
 * Under the eight symmetries of the square the 256 masks collapse into 51
 * orbits. Hensel gives each orbit a letter, unique within its neighbour count,
 * so `3i` names three neighbours in a row and `2i` names two opposite
 * orthogonal neighbours - the arrangement a blinker's centre cell sees.
 *
 * The groups below are transcribed from AlephAlpha/ca-rules. `hensel.test.ts`
 * recomputes the orbits from the symmetry group and asserts these groups are
 * exactly them, so a transcription slip cannot survive a test run.
 */

