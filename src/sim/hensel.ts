/**
 * One transition set per neighbour count. Bit `i` of `t[n]` selects the class
 * `LETTERS[n][i]`; a count with every bit set is the plain totalistic case.
 */
export type Transitions = Uint16Array

/** Every class of a count selected - what a bare digit in a rulestring means. */
export const ALL: readonly number[] = LETTERS.map((l) => (1 << l.length) - 1)
